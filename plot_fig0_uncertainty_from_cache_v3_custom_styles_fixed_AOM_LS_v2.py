#!/usr/bin/env python3
"""
Fast plotting script for fig_bulk0/fig_clump0 uncertainty regions.

This script does NOT run the ODE. It reads cached trajectory CSV files generated by:
    cache_fig0_uncertainty_trajectories_fast_v2.py

Main changes in this version:
    - Experimental points with labels "AOM_P_LS" and "AOM_Wegner_LS"
      are plotted together as the single series "AOM_LS".
    - Colors, line styles, marker styles, and legend labels are all defined
      in the USER SETTINGS section so you can edit them directly.
"""

